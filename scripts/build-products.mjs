#!/usr/bin/env node
// Generates static product pages and product cards from the live Shopify
// catalog (Storefront API). Run locally, review the diff, commit the output:
//
//   node scripts/build-products.mjs
//
// There is no build step on Vercel; this script's output is plain HTML.
//
// What it writes:
//   - shop/<handle>/index.html for every Shopify product that is NOT one of the
//     original 9 hand-built pages (those are the IDs in SHOPIFY_CONFIG in
//     assets/site.js). Header, footer and cart drawer are copied from
//     shop/off-black-tee/index.html so they stay identical to the other pages.
//   - Product cards between <!-- build:cards NAME --> and <!-- /build:cards -->
//     markers in shop/index.html, shop/consider/index.html and home/index.html:
//       consider       products in the Shopify "consider" collection (golf line)
//       hoodies        generated products with product type "Hoodies"
//       home-consider  first 3 Consider products, price only
//   - Product URLs between <!-- build:sitemap --> markers in sitemap.xml.
//
// Re-run after renaming products, changing photos or adding a drop. Pages it
// generated earlier for products no longer in Shopify are removed.

import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SITE = "https://hesedea.com";
const GENERATED_MARK = "<!-- Generated by scripts/build-products.mjs from Shopify. Do not edit by hand: edit the script and re-run it. -->";
const TEMPLATE_PAGE = "shop/off-black-tee/index.html";
const CARD_WIDTH = 840;

const read = (p) => readFileSync(join(ROOT, p), "utf8");
const write = (p, s) => { mkdirSync(dirname(join(ROOT, p)), { recursive: true }); writeFileSync(join(ROOT, p), s); };

/* ---------- config from assets/site.js (single source of truth) ---------- */
const siteJs = read("assets/site.js");
const DOMAIN = /domain:\s*"([^"]+)"/.exec(siteJs)[1];
const TOKEN = /storefrontAccessToken:\s*"([^"]+)"/.exec(siteJs)[1];
const LEGACY = {}; // shopify id -> slug, for the original 9 products
for (const m of siteJs.matchAll(/"([a-z0-9-]+)":\s*\{\s*id:\s*"(\d+)"/g)) LEGACY[m[2]] = m[1];

/* ---------- helpers ---------- */
const esc = (s) => String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&#x27;");
const numericId = (gid) => gid.split("/").pop();
const money = (n) => "$" + (n % 1 === 0 ? n.toFixed(0) : n.toFixed(2));

// Same rules as prettySize / prettyColor in assets/site.js
function prettySize(size) {
  const s = String(size ?? "").trim();
  const m = /^(x*)([sml])$/i.exec(s);
  if (m) return (m[1].length > 1 ? m[1].length + "X" : m[1].toUpperCase()) + m[2].toUpperCase();
  if (/^\d+x[sl]$/i.test(s)) return s.toUpperCase();
  return s;
}
function prettyColor(color) {
  const c = String(color ?? "").trim();
  if (c !== c.toLowerCase() && c !== c.toUpperCase()) return c;
  return c.toLowerCase().replace(/(^|[\s\/-])([a-z])/g, (_, sep, ch) => sep + ch.toUpperCase());
}
const opt = (v, name) => (v.selectedOptions.find((o) => o.name.toLowerCase() === name) || {}).value ?? null;
const unique = (xs) => [...new Set(xs)];

function scaled(img, width) {
  const w = Math.min(width, img.width || width);
  const h = img.width && img.height ? Math.round((img.height * w) / img.width) : Math.round(w * 1.25);
  return { w, h };
}

function summary(p) {
  const amounts = p.variants.map((v) => parseFloat(v.price.amount));
  const min = Math.min(...amounts), max = Math.max(...amounts);
  const colors = unique(p.variants.map((v) => opt(v, "color")).filter(Boolean));
  const sizes = unique(p.variants.map((v) => opt(v, "size")).filter(Boolean)).map(prettySize);
  const sizeText = sizes.length > 1 ? `${sizes[0]}&ndash;${sizes[sizes.length - 1]}` : sizes[0] || "";
  const colorText = colors.length > 1 ? `${colors.length} colors` : colors.length ? esc(prettyColor(colors[0])) : "";
  return {
    priceText: (max > min ? "From " : "") + money(min),
    min, colors, sizes,
    sub: [colorText, sizeText].filter(Boolean).join(" &middot; "),
  };
}

/* ---------- Storefront API ---------- */
async function storefront(query) {
  const res = await fetch(`https://${DOMAIN}/api/2025-01/graphql.json`, {
    method: "POST",
    headers: { "Content-Type": "application/json", "X-Shopify-Storefront-Access-Token": TOKEN },
    body: JSON.stringify({ query }),
  });
  const json = await res.json();
  if (!res.ok || json.errors) throw new Error("Storefront API error: " + JSON.stringify(json.errors || res.status));
  return json.data;
}

const data = await storefront(`{
  consider: collection(handle: "consider") { products(first: 100) { nodes { id } } }
  products(first: 250) { nodes {
    id handle title description descriptionHtml productType availableForSale
    seo { title description }
    collections(first: 10) { nodes { handle } }
    images(first: 30) { nodes { card: url(transform: { maxWidth: ${CARD_WIDTH} }) og: url(transform: { maxWidth: 1200 }) width height } }
    variants(first: 100) { nodes {
      id title availableForSale
      price { amount currencyCode }
      selectedOptions { name value }
      image { card: url(transform: { maxWidth: ${CARD_WIDTH} }) }
    } }
  } }
}`);

const warnings = [];
const all = data.products.nodes.map((p) => ({
  ...p,
  numericId: numericId(p.id),
  images: p.images.nodes,
  variants: p.variants.nodes,
  collections: p.collections.nodes.map((c) => c.handle),
}));
if (!data.consider) throw new Error('Shopify collection "consider" not found');
const considerOrder = data.consider.products.nodes.map((n) => n.id);

const generated = all.filter((p) => !LEGACY[p.numericId]);
const byId = Object.fromEntries(all.map((p) => [p.id, p]));
const consider = considerOrder.map((id) => byId[id]).filter((p) => p && !LEGACY[p.numericId]);
const hoodies = generated.filter((p) => !consider.includes(p) && /^hoodies?$/i.test(p.productType || ""));
for (const p of generated) {
  if (!consider.includes(p) && !hoodies.includes(p)) warnings.push(`${p.handle}: not in "consider" and not a hoodie, so it gets a page but no Shop card`);
  if (!p.images.length) warnings.push(`${p.handle}: has no images`);
  if (!p.availableForSale) warnings.push(`${p.handle}: nothing available for sale`);
  const colors = unique(p.variants.map((v) => opt(v, "color")).filter(Boolean));
  const imgPerColor = unique(colors.map((c) => (p.variants.find((v) => opt(v, "color") === c && v.image) || {}).image?.card?.split("?")[0]));
  if (colors.length > 1 && imgPerColor.length < colors.length) warnings.push(`${p.handle}: ${colors.length} colors but ${imgPerColor.length} distinct variant photo(s)`);
  if (!p.seo.description) warnings.push(`${p.handle}: no SEO description in Shopify, using the product description`);
}

/* ---------- original 9 pages, for related cards ---------- */
const legacyCards = {}; // shopify id -> card info parsed from its hand-built page
for (const dir of readdirSync(join(ROOT, "shop"), { withFileTypes: true })) {
  if (!dir.isDirectory()) continue;
  const file = `shop/${dir.name}/index.html`;
  if (!existsSync(join(ROOT, file))) continue;
  const html = read(file);
  if (html.includes(GENERATED_MARK)) continue;
  const slug = /data-shopify-buy="([^"]+)"/.exec(html)?.[1];
  const id = Object.keys(LEGACY).find((k) => LEGACY[k] === slug);
  if (!id) continue;
  const img = /<img src="([^"]+)" width="(\d+)" height="(\d+)"[^>]*alt="([^"]*)" data-product-main>/.exec(html);
  legacyCards[id] = {
    path: `/shop/${dir.name}`, slug,
    title: /<h1>(.*?)<\/h1>/.exec(html)[1],
    price: /data-shopify-price="[^"]+">([^<]+)</.exec(html)[1],
    sub: /<p class="product-sub">(.*?)<\/p>/.exec(html)[1],
    img: img && { src: img[1], w: img[2], h: img[3], alt: img[4] },
  };
}

/* ---------- card markup ---------- */
function productCard(p, { buy = true, stacked = false } = {}) {
  const s = summary(p);
  const url = `/shop/${p.handle}`;
  const img = p.images[0];
  const { w, h } = img ? scaled(img, CARD_WIDTH) : { w: 420, h: 525 };
  const media = img
    ? `<img class="shopify-img" src="${esc(img.card)}" width="${w}" height="${h}" loading="lazy" decoding="async" alt="HESEDEA ${esc(p.title)}">`
    : "";
  const lines = [
    `        <div class="product-card reveal">`,
    `          <div class="product-media"><a href="${url}" tabindex="-1" aria-hidden="true">${media}</a></div>`,
    `          <div class="product-info${stacked ? " product-info-stacked" : ""}"><h3><a href="${url}">${esc(p.title)}</a></h3><span class="product-price" data-shopify-price="${p.handle}" data-shopify-id="${p.numericId}">${s.priceText}</span></div>`,
    `          <p class="product-sub">${s.sub}</p>`,
  ];
  if (buy) lines.push(`          <div class="product-buy" data-shopify-buy="${p.handle}" data-shopify-id="${p.numericId}"><button class="btn btn-ghost btn-block" disabled>Notify Me</button></div>`);
  lines.push(`        </div>`);
  return lines.join("\n");
}

function legacyCard(c) {
  const img = c.img ? `<img src="${c.img.src}" width="${c.img.w}" height="${c.img.h}" loading="lazy" decoding="async" alt="${c.img.alt}">` : "";
  return [
    `        <div class="product-card reveal">`,
    `          <div class="product-media"><a href="${c.path}" tabindex="-1" aria-hidden="true">${img}</a></div>`,
    `          <div class="product-info"><h3><a href="${c.path}">${c.title}</a></h3><span class="product-price" data-shopify-price="${c.slug}">${c.price}</span></div>`,
    `          <p class="product-sub">${c.sub}</p>`,
    `        </div>`,
  ].join("\n");
}

// 3 others from the product's collection, in collection order, starting after it
function related(p) {
  const isConsider = consider.includes(p);
  let pool;
  if (isConsider) pool = consider;
  else {
    const coll = p.collections[0];
    pool = all.filter((q) => q.collections.includes(coll) && (!LEGACY[q.numericId] || legacyCards[q.id]));
  }
  const i = pool.indexOf(p);
  const ordered = [...pool.slice(i + 1), ...pool.slice(0, Math.max(i, 0))].filter((q) => q !== p);
  return ordered.slice(0, 3).map((q) => (LEGACY[q.numericId] ? legacyCard(legacyCards[q.id]) : productCard(q, { buy: false, stacked: isConsider })));
}

/* ---------- product page ---------- */
const template = read(TEMPLATE_PAGE);
const chromeTop = template.slice(template.indexOf("<body>"), template.indexOf("<main>"));
const chromeBottom = template.slice(template.indexOf("</main>"));

function cleanDescriptionHtml(html) {
  return (html || "")
    .replace(/<meta[^>]*>/gi, "")
    .replace(/\s(style|class|data-[a-z-]+)="[^"]*"/gi, "")
    .replace(/<span>([\s\S]*?)<\/span>/gi, "$1")
    .replace(/<p>\s*(&nbsp;)?\s*<\/p>/gi, "")
    .trim();
}

function productPage(p) {
  const s = summary(p);
  const isConsider = consider.includes(p);
  const url = `${SITE}/shop/${p.handle}`;
  const title = p.seo.title || `${p.title} | Hesedea`;
  const plain = (p.description || "").replace(/\s+/g, " ").trim();
  const desc = p.seo.description || (plain.length > 155 ? plain.slice(0, 152).replace(/\s+\S*$/, "") + "..." : plain);
  const img = p.images[0];
  const { w, h } = img ? scaled(img, CARD_WIDTH) : { w: 420, h: 525 };
  const eyebrow = isConsider ? "Consider &middot; Golf" : esc(p.productType || "Hesedea");
  const crumbs = [{ name: "Shop", item: `${SITE}/shop` }];
  if (isConsider) crumbs.push({ name: "Consider", item: `${SITE}/shop/consider` });
  crumbs.push({ name: p.title, item: url });

  const currency = p.variants[0]?.price.currencyCode || "USD";
  const offers = p.variants.map((v) => {
    const label = [opt(v, "color") && prettyColor(opt(v, "color")), opt(v, "size") && prettySize(opt(v, "size"))].filter(Boolean).join(" / ");
    return {
      "@type": "Offer", url, ...(label ? { name: label } : {}),
      price: parseFloat(v.price.amount).toFixed(2), priceCurrency: currency,
      availability: v.availableForSale ? "https://schema.org/InStock" : "https://schema.org/OutOfStock",
      itemCondition: "https://schema.org/NewCondition",
    };
  });
  // Static copy of what site.js (recordProductSchema) rebuilds from live data
  const productLd = {
    "@context": "https://schema.org",
    "@graph": [{
      "@type": "Product", name: p.title,
      image: p.images.map((i) => i.og),
      description: plain,
      brand: { "@type": "Brand", name: "Hesedea" },
      ...(s.sizes.length ? { size: s.sizes.join(", ") } : {}),
      offers: offers.length === 1 ? offers[0] : offers,
    }],
  };
  const breadcrumbLd = {
    "@context": "https://schema.org", "@type": "BreadcrumbList",
    itemListElement: crumbs.map((c, i) => ({ "@type": "ListItem", position: i + 1, name: c.name, item: c.item })),
  };
  const ld = (o) => JSON.stringify(o, null, 2).replace(/</g, "\\u003c");

  const crumbHtml = crumbs.map((c, i) => (i === crumbs.length - 1
    ? `<span aria-current="page">${esc(c.name)}</span>`
    : `<a href="${c.item.replace(SITE, "")}">${esc(c.name)}</a>`)).join(`<span aria-hidden="true">/</span>`);

  return `<!doctype html>
${GENERATED_MARK}
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<meta name="description" content="${esc(desc)}">
<link rel="canonical" href="${url}">
<link rel="icon" href="/favicon.ico" sizes="any">
<link rel="apple-touch-icon" href="/apple-touch-icon.png">
<meta name="theme-color" content="#8B2332">

<meta property="og:type" content="product">
<meta property="og:site_name" content="Hesedea">
<meta property="og:url" content="${url}">
<meta property="og:title" content="${esc(title)}">
<meta property="og:description" content="${esc(desc)}">
${img ? `<meta property="og:image" content="${esc(img.og)}">\n<meta property="og:image:alt" content="HESEDEA ${esc(p.title)}">` : ""}
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="${esc(title)}">
<meta name="twitter:description" content="${esc(desc)}">
${img ? `<meta name="twitter:image" content="${esc(img.og)}">` : ""}

<script type="application/ld+json">
${ld(breadcrumbLd)}
</script>
<script type="application/ld+json" id="product-jsonld">
${ld(productLd)}
</script>

<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="/assets/styles.css">
</head>
${chromeTop}<main>

<section class="view active" data-view="product">

  <section class="section product-detail-section">
    <div class="wrap">
      <nav class="breadcrumb" aria-label="Breadcrumb">${crumbHtml}</nav>

      <div class="product-detail" data-product="${p.handle}">
        <div class="product-detail-media">
          <div class="product-media">${img ? `<img class="shopify-img" src="${esc(img.card)}" width="${w}" height="${h}" decoding="async" alt="HESEDEA ${esc(p.title)}" data-product-main>` : ""}</div>
          <div class="product-thumbs" data-product-thumbs hidden></div>
        </div>

        <div class="product-detail-info">
          <span class="eyebrow">${eyebrow}</span>
          <h1>${esc(p.title)}</h1>
          <p class="product-detail-price"><span class="product-price" data-shopify-price="${p.handle}" data-shopify-id="${p.numericId}">${s.priceText}</span></p>
          <p class="product-sub">${s.sub}</p>
          <div class="product-buy" data-shopify-buy="${p.handle}" data-shopify-id="${p.numericId}"><button class="btn btn-ghost btn-block" disabled>Notify Me</button></div>

          <div class="product-description" data-product-description>
            ${cleanDescriptionHtml(p.descriptionHtml) || `<p>${esc(plain)}</p>`}
          </div>

          <div class="product-giving">
            <p>Net proceeds from every Hesedea purchase support <a href="/mully">Mully Children&rsquo;s Family</a>, caring for orphaned and vulnerable children in Kenya.</p>
          </div>
        </div>
      </div>
    </div>
  </section>

  <hr class="divider">

  <section class="section">
    <div class="wrap">
      <div class="section-head reveal">
        <div>
          <span class="eyebrow">Keep browsing</span>
          <h2>You might also like.</h2>
        </div>
        <a href="${isConsider ? "/shop/consider" : "/shop"}" class="btn btn-ghost">${isConsider ? "View all Consider" : "View all gear"}</a>
      </div>

      <div class="product-grid">
${related(p).join("\n")}
      </div>
    </div>
  </section>

</section>

${chromeBottom}`;
}

/* ---------- write everything ---------- */
function fillMarker(file, startMarker, endMarker, content) {
  const src = read(file);
  const a = src.indexOf(startMarker);
  const b = src.indexOf(endMarker, a);
  if (a === -1 || b === -1) throw new Error(`${file}: marker ${startMarker} not found`);
  const lineStart = src.lastIndexOf("\n", b) + 1;
  const indent = /^\s*$/.test(src.slice(lineStart, b)) ? src.slice(lineStart, b) : "";
  write(file, src.slice(0, a + startMarker.length) + "\n" + (content ? content + "\n" : "") + indent + src.slice(b));
}
const cards = (name, html, files) => files.forEach((f) => fillMarker(f, `<!-- build:cards ${name} -->`, "<!-- /build:cards -->", html));

const handles = new Set(generated.map((p) => p.handle));
for (const p of generated) write(`shop/${p.handle}/index.html`, productPage(p));

// remove pages this script generated for products that are gone from Shopify
for (const dir of readdirSync(join(ROOT, "shop"), { withFileTypes: true })) {
  const file = join(ROOT, "shop", dir.name, "index.html");
  if (dir.isDirectory() && !handles.has(dir.name) && existsSync(file) && readFileSync(file, "utf8").includes(GENERATED_MARK)) {
    rmSync(join(ROOT, "shop", dir.name), { recursive: true });
    warnings.push(`removed shop/${dir.name}: no longer in Shopify`);
  }
}

cards("consider", consider.map((p) => productCard(p, { stacked: true })).join("\n"), ["shop/index.html", "shop/consider/index.html"]);
cards("hoodies", hoodies.map((p) => productCard(p)).join("\n"), ["shop/index.html"]);
cards("home-consider", consider.slice(0, 3).map((p) => productCard(p, { buy: false, stacked: true })).join("\n"), ["home/index.html"]);
fillMarker("sitemap.xml", "<!-- build:sitemap -->", "<!-- /build:sitemap -->",
  generated.map((p) => `  <url><loc>${SITE}/shop/${p.handle}</loc></url>`).join("\n"));

console.log(`Generated ${generated.length} product pages (${consider.length} Consider, ${hoodies.length} hoodies).`);
for (const p of generated) console.log(`  /shop/${p.handle}  ${p.title}  ${summary(p).priceText}`);
if (warnings.length) console.log("\nWarnings:\n" + warnings.map((w) => "  - " + w).join("\n"));
